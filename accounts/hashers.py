"""
Hasher مخصص بعدد iterations أقل من الـ default بتاع Django 6.0 (1,200,000).

تاريخ القيمة (للسجل، بعد تشخيص كامل موثّق):
- 600,000: قياس مباشر جوه container web-store = 647.6ms
- 1,200,000 (default): قياس مباشر جوه container web-store = 1065.6ms
- العلاقة تقريبًا خطية مع عدد الـ iterations على نفس الهاردوير/الحاوية،
  فالقيم الأقل من كده (300k-400k) متوقع تتبع نفس النسبة تقريبًا:
    300,000 → ~325ms تقريبًا (تقدير، مش مقاس مباشر)
    350,000 → ~380ms تقريبًا (تقدير)
    400,000 → ~430ms تقريبًا (تقدير)

القيمة الحالية مختارة كمنتصف النطاق المطلوب (300k-400k). عدّل الرقم
تحت مباشرة لو عايز نقطة تانية جوه نفس النطاق — مفيش داعي لأي تغيير
تاني في أي ملف غيره.

تنبيه أمني: النطاق ده أقل من أي default رسمي استخدمه Django في أي
إصدار (أقل default تاريخي كان 600,000 في Django 4.2). ده تريدأوف
واعي بين سرعة تسجيل الدخول ومقاومة brute-force في حالة تسريب الداتابيز،
مش مجرد "رجوع لمعيار قديم" زي اختيار 600,000.
"""
from django.contrib.auth.hashers import PBKDF2PasswordHasher


class FastPBKDF2Hasher(PBKDF2PasswordHasher):
    iterations = 350_000
